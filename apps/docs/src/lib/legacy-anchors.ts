/** Where a bookmarked `url` points now, with its query, or undefined when the table doesn't name its heading. */
export function legacyAnchor(url: URL) {
  const target = LEGACY_ANCHORS[url.pathname]?.[url.hash.slice(1)];
  // Only the table's own entries: `#constructor` must not find Object's.
  if (typeof target !== 'string') return undefined;
  const moved = new URL(target, url);
  moved.search = url.search;
  return moved;
}
